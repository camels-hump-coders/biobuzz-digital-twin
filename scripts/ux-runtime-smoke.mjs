import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mockRuntime } from './ux-fixtures.mjs';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const writes=await mockRuntime(page);
await page.addInitScript(()=>localStorage.setItem('biobuzz-twin',JSON.stringify({settingsAutoLoad:false,pip:false,stadium:false,opponents:false})));
await page.goto('http://localhost:5173/?runtime=1&ci=1');
await page.waitForFunction(()=>document.querySelector('.runtime-guidance')?.textContent.includes('Runtime connected'));
assert.match(await page.locator('.runtime-guidance').innerText(), /initialize/i);
assert.equal(await page.locator('.runtime-guidance').getByRole('combobox',{name:'OpMode',exact:true}).isVisible(),true);
const sync=page.getByRole('region',{name:'Project sync and save'});
// The named section has real save controls, with no disclosure to open.
assert.equal(await page.locator('.robot-config-sync').getByRole('button',{name:'Save robot configuration',exact:true}).isVisible(),true);
await page.locator('.robot-config-sync').getByRole('button',{name:'Save robot configuration',exact:true}).click();
await page.getByRole('dialog',{name:'Save robot configuration',exact:true}).getByRole('button',{name:'Keep in simulator',exact:true}).click();
assert.equal(writes.settings.length,0);
await page.locator('.robot-config-sync').getByRole('button',{name:'Save robot configuration',exact:true}).click();
await page.getByRole('dialog',{name:'Save robot configuration',exact:true}).getByRole('button',{name:'Save to project',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('.robot-config-sync')?.textContent.includes('In sync'));
assert.equal(writes.settings.length,1);
assert.equal(await page.locator('.teamcode-sync').getByRole('button',{name:'Open settings editor',exact:true}).isVisible(),true);

assert.equal(await page.getByText('Connect your host, choose a program, then initialize and start. Or try the robot manually first.',{exact:true}).count(),0);
for (const name of ['Infinite ammo','Opponents']) {
  const toggle=page.locator('#quick-controls').getByRole('button',{name,exact:true});
  const before=await toggle.getAttribute('aria-pressed'); await toggle.click();
  await page.waitForFunction(({name,before})=>[...document.querySelectorAll('#quick-controls button')].find(b=>b.textContent===name)?.getAttribute('aria-pressed')!==before,{name,before});
}
for (const value of ['hitmap','reach','none']) {
  await page.locator('#quick-controls').getByRole('combobox',{name:'Field overlay'}).selectOption(value);
  assert.deepEqual(await page.evaluate(()=>[window.__twin.state.overlays.hitmap,window.__twin.state.overlays.reach]),[value==='hitmap',value==='reach']);
}
await page.locator('#quick-controls').getByRole('button',{name:'Cameras',exact:true}).click();
const preview=page.locator('#pips .pip').first(); await preview.waitFor({state:'visible'});
const small=(await preview.boundingBox()).width;
await preview.getByRole('button',{name:'Enlarge camera previews',exact:true}).click();
assert.ok((await preview.boundingBox()).width>small);
await page.waitForTimeout(1200);
await page.screenshot({path:'/tmp/biobuzz-runtime-refinement.png'});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'/tmp/biobuzz-runtime-mobile.png'});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.setViewportSize({width:1440,height:1000});
const program=page.locator('.runtime-guidance').getByRole('combobox',{name:'OpMode',exact:true});
const programBox=await program.boundingBox();
const initBox=await page.getByRole('button',{name:'Initialize program',exact:true}).boundingBox();
assert.ok(programBox.y+programBox.height<=initBox.y);
await program.selectOption('Demo: Autonomous');
await page.getByRole('button',{name:'Initialize program',exact:true}).click();
await page.waitForFunction(()=>window.__twin.link.currentOpMode==='Demo: Autonomous');
assert.equal(await page.locator('.runtime-guidance').getByRole('combobox',{name:'OpMode',exact:true}).isDisabled(),true);
await page.waitForFunction(()=>document.querySelector('.runtime-guidance')?.textContent.includes('Initialized · ready to start'));

await page.getByRole('button',{name:'Start program',exact:true}).click();
await page.waitForFunction(()=>window.__twin.link.status==='RUNNING');
await page.getByRole('button',{name:'Practice',exact:true}).click();
assert.equal(await page.locator('#control-dock').getByRole('button',{name:'Stop',exact:true}).isEnabled(),true);
assert.equal(await page.getByRole('button',{name:'Shoot · Space',exact:true}).isDisabled(),true);
await page.locator('#control-dock').getByRole('button',{name:'Stop',exact:true}).click();
await page.getByRole('button',{name:'Run TeamCode',exact:true}).click();
await page.getByRole('button',{name:'Open settings editor',exact:true}).click();
const dialog=page.getByRole('dialog').filter({has:page.getByRole('heading',{name:'TeamCode settings',exact:true})});
const power=dialog.getByRole('spinbutton',{name:'Drive.max Power exact value',exact:true});
console.log('labels',await dialog.locator('input,select').evaluateAll(es=>es.map(e=>e.getAttribute('aria-label'))));
await power.fill('0.5');await power.press('Tab');
await dialog.getByRole('button',{name:'Review 1 changed file',exact:true}).click();
await page.getByRole('dialog',{name:'Save TeamCode settings',exact:true}).getByRole('button',{name:'Keep in simulator',exact:true}).click();
assert.equal(writes.length,0);
await dialog.getByRole('button',{name:'Review 1 changed file',exact:true}).click();
await page.getByRole('dialog',{name:'Save TeamCode settings',exact:true}).getByRole('button',{name:'Save to project',exact:true}).click();
await page.waitForFunction(()=>window.__twin.link.assets.some(f=>f.text.includes('0.5')));
assert.equal(writes.length,1);
await page.screenshot({path:'/tmp/biobuzz-new-editor.png'});
assert.equal(errors.length,0, errors.join('\n'));
console.log('Runtime UI passed: INIT/START/STOP, persistent Stop, ownership, editor, save review/cancel/commit (mock host).');
const disabledPage=await browser.newPage();
await mockRuntime(disabledPage);
await disabledPage.addInitScript(()=>localStorage.setItem('biobuzz-twin',JSON.stringify({runtimeEnabled:false,settingsAutoLoad:false,pip:false,stadium:false})));
await disabledPage.goto('http://localhost:5173/?ci=1');
await disabledPage.getByRole('button',{name:'Run TeamCode',exact:true}).click();
await disabledPage.getByRole('button',{name:'Enable runtime',exact:true}).click();
await disabledPage.waitForFunction(()=>document.querySelector('.runtime-guidance')?.textContent.includes('Runtime connected'));
await disabledPage.getByRole('checkbox',{name:'Connect to runtime host',exact:true}).uncheck();
await disabledPage.waitForFunction(()=>!window.__twin.link.connected);
await disabledPage.waitForTimeout(1800);
assert.equal(await disabledPage.evaluate(()=>window.__twin.link.connected),false);
await disabledPage.getByRole('button',{name:'Enable runtime',exact:true}).click();
await disabledPage.waitForFunction(()=>window.__twin.link.connected);
console.log('Enable/disable/re-enable runtime passed.');
await browser.close();
